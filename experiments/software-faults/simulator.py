import hashlib
import time
import uuid
from typing import Dict, List
import requests

import sys
import os
sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from parsers.event_parser import (
    GlitchEventModel,
    EventSource,
    EventType,
    Severity,
    VerificationStatus,
    DefensiveResponse,
)

class FaultSimulator:
    """
    Controlled Software Fault Simulator for GLITCHGUARD.
    All events generated by this simulator explicitly set:
      source = EventSource.SOFTWARE_SIMULATOR
    Never represents simulated anomalies as physical hardware glitches.
    """

    def __init__(self, backend_url: str = "http://127.0.0.1:8000"):
        self.backend_url = backend_url
        self.session_id = f"sim-{uuid.uuid4().hex[:8]}"

    def _post_event(self, event: GlitchEventModel) -> bool:
        try:
            resp = requests.post(
                f"{self.backend_url}/api/events/record",
                json=event.model_dump(),
                timeout=2.0
            )
            return resp.status_code == 200
        except Exception:
            return False

    def experiment_a_invalid_integrity(self, iterations: int = 20) -> List[GlitchEventModel]:
        """Experiment A: Inject deliberately invalid test data into integrity verification."""
        events = []
        payload = b"CRITICAL_SYSTEM_STATE_RECORD_V1"
        expected_hash = hashlib.sha256(payload).hexdigest()

        for i in range(iterations):
            # Inject bit flip in payload
            corrupted = bytearray(payload)
            corrupted[0] ^= 0xFF
            observed_hash = hashlib.sha256(corrupted).hexdigest()

            event = GlitchEventModel(
                source=EventSource.SOFTWARE_SIMULATOR,
                event_type=EventType.INTEGRITY_FAILURE,
                severity=Severity.HIGH,
                experiment_id=f"EXP-A-INTEGRITY-{i+1:03d}",
                device_session_id=self.session_id,
                evidence={
                    "expected_hash": expected_hash,
                    "observed_hash": observed_hash,
                    "tampered_byte_index": 0,
                    "simulation": True,
                },
                verification_status=VerificationStatus.FAILED,
                response=DefensiveResponse.QUARANTINED,
            )
            self._post_event(event)
            events.append(event)
            time.sleep(0.01)
        return events

    def experiment_b_heartbeat_failure(self, timeout_ms: int = 500) -> GlitchEventModel:
        """Experiment B: Simulate missing heartbeat from test application."""
        event = GlitchEventModel(
            source=EventSource.SOFTWARE_SIMULATOR,
            event_type=EventType.HEARTBEAT_TIMEOUT,
            severity=Severity.HIGH,
            experiment_id="EXP-B-HEARTBEAT-001",
            device_session_id=self.session_id,
            evidence={
                "target_subsystem": "crypto-worker",
                "last_seen_delta_ms": timeout_ms + 150,
                "threshold_ms": timeout_ms,
                "simulation": True,
            },
            verification_status=VerificationStatus.ERROR,
            response=DefensiveResponse.QUARANTINED,
        )
        self._post_event(event)
        return event

    def experiment_c_interrupted_execution(self) -> GlitchEventModel:
        """Experiment C: Simulate unexpected process termination during secure operation."""
        event = GlitchEventModel(
            source=EventSource.SOFTWARE_SIMULATOR,
            event_type=EventType.ANOMALY,
            severity=Severity.HIGH,
            experiment_id="EXP-C-INTERRUPT-001",
            device_session_id=self.session_id,
            evidence={
                "stage": "KEY_DERIVATION_STEP_2",
                "aborted_unexpectedly": True,
                "simulation": True,
            },
            verification_status=VerificationStatus.PENDING,
            response=DefensiveResponse.VERIFYING,
        )
        self._post_event(event)
        return event

    def experiment_d_corrupted_test_data(self) -> GlitchEventModel:
        """Experiment D: Introduce controlled corruption into a buffer."""
        event = GlitchEventModel(
            source=EventSource.SOFTWARE_SIMULATOR,
            event_type=EventType.INTEGRITY_FAILURE,
            severity=Severity.MEDIUM,
            experiment_id="EXP-D-BUFFER-001",
            device_session_id=self.session_id,
            evidence={
                "buffer_id": "SECURE_STORAGE_SLOT_0",
                "crc32_expected": "0x4F12B980",
                "crc32_calculated": "0x00000000",
                "simulation": True,
            },
            verification_status=VerificationStatus.FAILED,
            response=DefensiveResponse.QUARANTINED,
        )
        self._post_event(event)
        return event

    def experiment_e_repeated_anomalies(self, count: int = 5) -> List[GlitchEventModel]:
        """Experiment E: Generate repeated synthetic anomalies leading to lockdown."""
        events = []
        for i in range(count):
            resp = DefensiveResponse.QUARANTINED if i < 4 else DefensiveResponse.LOCKDOWN
            event = GlitchEventModel(
                source=EventSource.SOFTWARE_SIMULATOR,
                event_type=EventType.ANOMALY,
                severity=Severity.CRITICAL if resp == DefensiveResponse.LOCKDOWN else Severity.HIGH,
                experiment_id=f"EXP-E-REPEATED-{i+1:03d}",
                device_session_id=self.session_id,
                evidence={
                    "repetition_index": i + 1,
                    "cumulative_faults": i + 1,
                    "simulation": True,
                },
                verification_status=VerificationStatus.FAILED,
                response=resp,
            )
            self._post_event(event)
            events.append(event)
            time.sleep(0.01)
        return events
