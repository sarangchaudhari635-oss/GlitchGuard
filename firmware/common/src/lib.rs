//! glitchguard-common — Shared types, event schema, and protocol definitions.
//!
//! This crate is `no_std` compatible. It defines the core event types used
//! by all GLITCHGUARD firmware crates and must remain free of OS-specific
//! dependencies.
//!
//! # Stability
//! All public types in this crate are part of the wire protocol. Breaking
//! changes require a schema version bump in `EventSchema::schema_version`.

#![no_std]
#![forbid(unsafe_code)]

use heapless::String;
use serde::{Deserialize, Serialize};

// ─────────────────────────────────────────────────────────────────────────────
// Schema version
// ─────────────────────────────────────────────────────────────────────────────

/// Wire protocol schema version. Increment the major number on breaking changes.
pub const SCHEMA_VERSION: &str = "1.0";

// ─────────────────────────────────────────────────────────────────────────────
// Source — where did this event originate?
// ─────────────────────────────────────────────────────────────────────────────

/// The origin of a security event.
///
/// This field is critical for distinguishing real hardware observations from
/// software simulations. It MUST NOT be overridden or spoofed.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum EventSource {
    /// Value read directly from a physical hardware sensor register.
    /// Only use this when the value comes from an actual register read.
    HardwareSensor,
    /// Generated by the Python fault simulation framework on the host.
    SoftwareSimulator,
    /// Detected by the Xous runtime monitoring service (software observation).
    RuntimeMonitor,
    /// Derived from hardware reset source information.
    ResetController,
}

// ─────────────────────────────────────────────────────────────────────────────
// Event type classification
// ─────────────────────────────────────────────────────────────────────────────

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "SCREAMING_SNAKE_CASE")]
pub enum EventType {
    Normal,
    Anomaly,
    IntegrityFailure,
    HardwareWarning,
    ResetEvent,
    HeartbeatTimeout,
    Recovery,
    SensorUnavailable,
}

// ─────────────────────────────────────────────────────────────────────────────
// Severity
// ─────────────────────────────────────────────────────────────────────────────

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize)]
#[serde(rename_all = "SCREAMING_SNAKE_CASE")]
pub enum Severity {
    Info,
    Low,
    Medium,
    High,
    Critical,
}

// ─────────────────────────────────────────────────────────────────────────────
// Verification status
// ─────────────────────────────────────────────────────────────────────────────

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "SCREAMING_SNAKE_CASE")]
pub enum VerificationStatus {
    Passed,
    Failed,
    Skipped,
    Pending,
    Error,
}

// ─────────────────────────────────────────────────────────────────────────────
// Defensive response
// ─────────────────────────────────────────────────────────────────────────────

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "SCREAMING_SNAKE_CASE")]
pub enum DefensiveResponse {
    None,
    Logged,
    Alert,
    Quarantined,
    Verifying,
    Recovered,
    Lockdown,
}

// ─────────────────────────────────────────────────────────────────────────────
// Hardware capability status
// ─────────────────────────────────────────────────────────────────────────────

/// Status of a hardware capability as determined by the hardware-observer.
///
/// A capability is only AVAILABLE once it has been physically verified on the
/// actual board. IMPLEMENTED alone is insufficient.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "SCREAMING_SNAKE_CASE")]
pub enum CapabilityStatus {
    /// Confirmed available and physically verified on this board revision.
    Available,
    /// Chip feature exists but not present on this board revision.
    Unavailable,
    /// Not supported by the Baochip-1x silicon.
    Unsupported,
    /// Existence suspected from documentation but not physically verified.
    NotVerified,
    /// Error encountered when attempting to access this interface.
    Error,
}

// ─────────────────────────────────────────────────────────────────────────────
// Recovery FSM state
// ─────────────────────────────────────────────────────────────────────────────

/// Security finite state machine states.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "SCREAMING_SNAKE_CASE")]
pub enum SecurityState {
    Normal,
    SuspectedAnomaly,
    Quarantined,
    Verifying,
    Recovered,
    Lockdown,
}

// ─────────────────────────────────────────────────────────────────────────────
// Core event structure (no_std, heapless strings)
// ─────────────────────────────────────────────────────────────────────────────

/// A GLITCHGUARD security event in its firmware-internal representation.
///
/// This struct uses `heapless::String` for no_std compatibility. The host-side
/// Python models use standard `str` with full Pydantic validation.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct GlitchEvent {
    pub schema_version: &'static str,
    /// UUID v4 as a 36-char string
    pub event_id: String<36>,
    /// Monotonic nanosecond timestamp from the Xous system clock
    pub timestamp_ns: u64,
    pub source: EventSource,
    pub event_type: EventType,
    pub severity: Severity,
    /// e.g. "GG-EXP-A-001" or "BASELINE"
    pub experiment_id: String<32>,
    /// Non-sensitive per-boot session identifier
    pub device_session_id: String<32>,
    pub verification_status: VerificationStatus,
    pub response: DefensiveResponse,
}

impl GlitchEvent {
    /// Construct a minimal INFO-level heartbeat event.
    pub fn heartbeat(
        event_id: String<36>,
        timestamp_ns: u64,
        session_id: String<32>,
        _sequence: u32,
    ) -> Self {
        let mut experiment_id = String::new();
        let _ = experiment_id.push_str("BASELINE");

        Self {
            schema_version: SCHEMA_VERSION,
            event_id,
            timestamp_ns,
            source: EventSource::RuntimeMonitor,
            event_type: EventType::Normal,
            severity: Severity::Info,
            experiment_id,
            device_session_id: session_id,
            verification_status: VerificationStatus::Skipped,
            response: DefensiveResponse::Logged,
        }
    }
}

// ─────────────────────────────────────────────────────────────────────────────
// Tests
// ─────────────────────────────────────────────────────────────────────────────

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn severity_ordering() {
        assert!(Severity::Info < Severity::Low);
        assert!(Severity::Low < Severity::Medium);
        assert!(Severity::Medium < Severity::High);
        assert!(Severity::High < Severity::Critical);
    }

    #[test]
    fn event_source_simulation_not_hardware() {
        // Ensure the discriminant for simulated events is distinct from hardware
        assert_ne!(EventSource::SoftwareSimulator, EventSource::HardwareSensor);
    }

    #[test]
    fn security_state_enum_exists() {
        let s = SecurityState::Normal;
        assert_eq!(s, SecurityState::Normal);
    }
}
